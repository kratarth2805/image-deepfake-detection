import torch
import torch.nn as nn
from torchvision import models

class FrequencyBranch(nn.Module):
    """
    Extracts frequency-domain representations using 2D Fast Fourier Transform (FFT).
    Processes spectral magnitude artifacts generated by synthetic image pipelines.
    """
    def __init__(self):
        super(FrequencyBranch, self).__init__()
        self.conv_net = nn.Sequential(
            nn.Conv2d(3, 32, kernel_size=3, stride=2, padding=1),
            nn.BatchNorm2d(32),
            nn.ReLU(),
            nn.MaxPool2d(2),
            
            nn.Conv2d(32, 64, kernel_size=3, stride=2, padding=1),
            nn.BatchNorm2d(64),
            nn.ReLU(),
            
            nn.AdaptiveAvgPool2d((1, 1)),
            nn.Flatten()
        )

    def forward(self, x):
        # Compute 2D Fast Fourier Transform across spatial dimensions (H, W)
        fft = torch.fft.fft2(x)
        fft_shift = torch.fft.fftshift(fft)
        
        # Log-magnitude spectrum for dynamic range compression
        magnitude_spectrum = torch.log(torch.abs(fft_shift) + 1e-8)
        
        return self.conv_net(magnitude_spectrum)


class SpatialFrequencyHybridDetector(nn.Module):
    """
    Dual-stream architecture combining spatial features from ResNet-18
    and frequency features from the FFT branch.
    """
    def __init__(self, num_classes=2, freeze_spatial_backbone=True):
        super(SpatialFrequencyHybridDetector, self).__init__()
        
        # Spatial Stream: Pretrained ResNet-18
        spatial_weights = models.ResNet18_Weights.DEFAULT
        resnet = models.resnet18(weights=spatial_weights)
        
        if freeze_spatial_backbone:
            for param in resnet.parameters():
                param.requires_grad = False
                
        # Retain feature extractor up to the average pooling layer (512 dimensions)
        self.spatial_stream = nn.Sequential(*list(resnet.children())[:-1])
        
        # Frequency Stream: FFT CNN (64 dimensions)
        self.frequency_stream = FrequencyBranch()
        
        # Fusion Classifier: 512 + 64 = 576 dimensions
        self.classifier = nn.Sequential(
            nn.Linear(512 + 64, 256),
            nn.ReLU(),
            nn.Dropout(0.4),
            nn.Linear(256, num_classes)
        )

    def forward(self, x):
        # Spatial feature extraction
        spatial_feat = self.spatial_stream(x)
        spatial_feat = torch.flatten(spatial_feat, 1)  # shape: [B, 512]
        
        # Frequency feature extraction
        freq_feat = self.frequency_stream(x)           # shape: [B, 64]
        
        # Feature fusion (concatenation)
        fused = torch.cat((spatial_feat, freq_feat), dim=1)  # shape: [B, 576]
        
        return self.classifier(fused)

